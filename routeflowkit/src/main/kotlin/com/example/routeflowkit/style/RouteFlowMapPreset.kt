package com.example.routeflowkit.style

/** Provider-independent map presentation presets supported by RouteFlowKit. */
enum class RouteFlowMapPreset {
    /** The map provider's standard appearance. */
    Default,

    /** A light, low-noise presentation that keeps the route visually prominent. */
    Clean,

    /** An ultra-minimal presentation with useful geometry and almost no map labels. */
    Minimal,
}
